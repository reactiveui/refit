using System.Diagnostics.CodeAnalysis;
using System.Runtime.CompilerServices;

namespace Refit;

/// <summary>
/// Provides static methods for creating request builders for Refit interface types. This class enables the
/// generation of strongly-typed HTTP client implementations based on interface definitions and optional settings.
/// </summary>
/// <remarks>Request builders generated by this class use reflection to analyze the provided interface
/// type and create implementations for HTTP API calls. All members of this class are thread-safe and can be used
/// concurrently across multiple threads.</remarks>
public static class RequestBuilder
{
    /// <summary>Creates an HTTP request builder for the specified interface type.</summary>
    /// <typeparam name="T">The interface type that defines the HTTP API methods to be implemented by the request builder.</typeparam>
    /// <param name="settings">The Refit settings to use for configuring the request builder. May be null to use default settings.</param>
    /// <returns>An instance of IRequestBuilder T that can be used to construct HTTP requests for the specified interface type.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    [SuppressMessage(
        "Design",
        "SST2307:Generic method type parameters should be inferable from the parameters",
        Justification = "Type parameter intentionally specified explicitly by callers.")]
    public static IRequestBuilder<T> ForType<T>(RefitSettings? settings) =>
        RequestBuilderFactory.Create<T>(settings);

    /// <summary>Creates a request builder for the specified type, enabling construction of requests against its members.</summary>
    /// <typeparam name="T">The type for which to create the request builder.</typeparam>
    /// <returns>An object that can be used to build requests for the specified type.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    [SuppressMessage(
        "Design",
        "SST2307:Generic method type parameters should be inferable from the parameters",
        Justification = "Type parameter intentionally specified explicitly by callers.")]
    public static IRequestBuilder<T> ForType<T>() => RequestBuilderFactory.Create<T>(null);

    /// <summary>Creates a request builder for the specified Refit interface.</summary>
    /// <param name="refitInterfaceType">The interface type that defines the HTTP API contract, including a closed generic interface, decorated with Refit attributes.</param>
    /// <param name="settings">Optional settings to customize the behavior of the generated request builder. If null, default settings are used.</param>
    /// <returns>An IRequestBuilder instance that can be used to construct HTTP requests for the specified interface.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static IRequestBuilder ForType(Type refitInterfaceType, RefitSettings? settings) =>
        RequestBuilderFactory.Create(refitInterfaceType, settings);

    /// <summary>Creates a request builder for the specified Refit interface type.</summary>
    /// <param name="refitInterfaceType">The interface type that defines the Refit API contract, including a closed generic interface, decorated with Refit attributes.</param>
    /// <returns>An IRequestBuilder instance that can be used to construct HTTP requests for the specified interface type.</returns>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static IRequestBuilder ForType(Type refitInterfaceType) => ForType(refitInterfaceType, null);
}
